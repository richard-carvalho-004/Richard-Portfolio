"""Generate the hero's swirl-cloud SVGs.

    python tools/swirl.py Images/swirl-corner.svg Images/swirl-edge.svg
"""
import math, sys
INK = "#4a3b30"
CRIMSON = "#9b1c31"
FILL = "#f6eddc"
GAP, SW = 11, 1.4

def spiral(cx, cy, rmax, turns=2.4, a0=0.0):
    n = int(turns * 40); pts = []
    for i in range(n + 1):
        t = i / n; a = a0 + t * turns * 2 * math.pi; r = rmax * t
        pts.append(f"{cx + r*math.cos(a):.1f} {cy + r*math.sin(a):.1f}")
    return "M" + "L".join(pts)

def cloud(lobes, w, h, note):
    out = []
    k = 0
    while True:
        active = [(cx, cy, r - k*GAP) for cx, cy, r in lobes if r - k*GAP >= max(r*0.36, 10)]
        if not active: break
        col, op = (CRIMSON, 0.8) if k == 1 else (INK, 0.85)
        # wide strokes first, fills on top -> only the outer union contour stays visible
        out.append(f'<g fill="none" stroke="{col}" stroke-opacity="{op}" stroke-width="{SW*2}">' +
                   "".join(f'<circle cx="{cx}" cy="{cy}" r="{r:.1f}"/>' for cx, cy, r in active) + "</g>")
        out.append(f'<g fill="{FILL}">' + "".join(f'<circle cx="{cx}" cy="{cy}" r="{r:.1f}"/>' for cx, cy, r in active) + "</g>")
        k += 1
    for i, (cx, cy, r) in enumerate(lobes):
        kk = 0
        while r - (kk+1)*GAP >= max(r*0.36, 10): kk += 1
        out.append(f'<path d="{spiral(cx, cy, r - kk*GAP - 3, a0=i*1.3)}" fill="none" stroke="{INK}" '
                   f'stroke-opacity="0.85" stroke-width="{SW}" stroke-linecap="round"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">\n<!-- {note} -->\n'
            + "\n".join(out) + "\n</svg>\n")

# corner: hugs the top-left, cut off by the top and left edges; inner edge is scalloped
corner = [
    (30, 20, 140), (220, -20, 115), (390, -40, 100), (560, -40, 85), (-20, 210, 110), (-30, 350, 80),
    (150, 120, 72), (305, 75, 62), (450, 45, 52), (590, 35, 40), (65, 260, 60), (20, 375, 42),
    (230, 165, 45), (125, 225, 40), (375, 112, 36), (520, 78, 30), (75, 330, 30), (280, 205, 26),
]
# edge: a side cloud, cut off only by the left edge
edge = [
    (-30, 150, 95), (-40, 300, 110), (-30, 450, 85),
    (55, 110, 52), (70, 230, 60), (60, 360, 58), (50, 480, 40),
    (115, 170, 34), (130, 300, 38), (110, 410, 32), (95, 60, 30),
]
open(sys.argv[1], "w", encoding="utf-8").write(cloud(corner, 640, 400, "original swirl-cloud corner, generated by tools/swirl.py"))
open(sys.argv[2], "w", encoding="utf-8").write(cloud(edge, 180, 540, "original swirl-cloud edge, generated by tools/swirl.py"))
print("written")
